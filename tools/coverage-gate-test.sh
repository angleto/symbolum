#!/bin/sh
# Run `tools/coverage-gate.sh` against a stub build tool, in every state its verdict distinguishes.
#
# WHY STUBS AND NOT THE REAL GATE. The real one is twenty minutes and a quiet machine, and the
# states worth checking are the ones where it does NOT finish: a red suite and a run killed part
# way. Producing either for real means breaking a test on purpose or killing a build at the right
# second, which is a thing somebody does once by hand and nobody repeats. A stub that writes the
# reports it was told to and exits the code it was told to reaches every state in a second, and
# the subject's whole content is what it says about which state it is in.
#
# WHAT IT DOES NOT COVER, named rather than left to be assumed: whether `clean coverage test
# coverageReport` is the right command, and whether scoverage writes where this expects. The
# first is `build.sbt`'s and `CLAUDE.md`'s; the second is checked by the gate's own real runs,
# where a wrong path would read as "never asked" on a run that plainly finished.

set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
subject="$here/coverage-gate.sh"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT INT TERM

harness_name=coverage-gate-test
. "$here/test-harness.sh"

failures=0

# HOW MANY MODULES THE SUBJECT EXPECTS, asked the way the subject asks, because the number is a
# property of the checkout and writing it here by hand would make this file wrong the day a module
# lands. The stub is told how many reports to write in terms of it.
modules=0
for d in "$here"/../modules/*/; do
    [ -d "$d/src/main" ] && modules=$((modules + 1))
done
if [ "$modules" -lt 2 ]; then
    echo "$harness_name: the checkout has $modules module(s) with sources; the cases below need at least 2" >&2
    exit 2
fi

# The stub. It writes `$STUB_REPORTS` reports into the real tree's report paths and exits
# `$STUB_EXIT`. Writing into the real tree is deliberate and is the one thing here that is not
# hermetic: the subject looks for reports where scoverage puts them, so a stub writing anywhere
# else would be testing a different path than the one that matters. The files it writes are
# harmless — a `scoverage.xml` is regenerated by any real run, and the paths already exist on any
# tree that has run the gate — and the case list restores nothing because there is nothing a real
# run would not overwrite.
mkdir -p "$work/bin"
cat > "$work/bin/sbt-stub" <<'STUB'
#!/bin/sh
root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
echo "STUB-SBT $*"
written=0
for d in "$STUB_ROOT"/modules/*/; do
    [ -d "$d/src/main" ] || continue
    [ "$written" -ge "$STUB_REPORTS" ] && break
    mkdir -p "$d/target/scala-3.3.5/scoverage-report"
    echo '<statements/>' > "$d/target/scala-3.3.5/scoverage-report/scoverage.xml"
    written=$((written + 1))
done
exit "$STUB_EXIT"
STUB
chmod +x "$work/bin/sbt-stub"

root=$(CDPATH= cd -- "$here/.." && pwd)

# Every report older than the run, which is the state a fresh checkout and a `clean` both leave.
# Done by touching them into the past rather than by deleting: deleting would also pass a subject
# that had stopped looking at the timestamp and only checked existence, and the run that this card
# is about had reports on disk from the PREVIOUS run the whole time.
age_them() {
    for d in "$root"/modules/*/; do
        [ -d "$d/src/main" ] || continue
        f="$d/target/scala-3.3.5/scoverage-report/scoverage.xml"
        [ -f "$f" ] || { mkdir -p "$(dirname "$f")"; echo '<statements/>' > "$f"; }
        touch -t 202001010000 "$f"
    done
}

run_case() {
    age_them
    report=$(STUB_ROOT="$root" STUB_REPORTS="$1" STUB_EXIT="$2" \
        COVERAGE_GATE_SBT="$work/bin/sbt-stub" sh "$subject" 2>&1) || true
    status=$?
}

echo "$harness_name: the three answers, and that they are three"

# 1. THE ORDINARY PASS. Every module reports and the build is green.
run_case "$modules" 0
holds "a green run says the floors were asked and held" "asked of all $modules modules and they held"
lacks "a green run does not say they went unasked" "NEVER ASKED"

# 2. A FLOOR FELL. Every module reports and the build is red. This is the case the old command
# already distinguished, and it has to keep reading differently from case 3 or the addition is
# noise.
run_case "$modules" 1
holds "a floor falling says the floors were asked" "asked of all $modules modules and the build exited"
lacks "a floor falling is not reported as unasked" "NEVER ASKED"

# 3. THE DEFECT. The suite went red, so `coverageReport` never ran and nothing wrote a report.
# The old command's log says nothing at all here, which is what the card is about.
run_case 0 1
holds "a red suite says the floors were never asked" "THE FLOORS WERE NEVER ASKED"
holds "and says how to get the report without paying for the suite again" "coverage coverageReport"
lacks "and does not claim they held" "they held"

# 4. THE SECOND SHAPE, a run that died part way: some modules reported and the rest did not. The
# verdict must name the shortfall rather than round it to either of the two above, because a
# reader of a partial report is the one most likely to believe a number about the whole build.
run_case 1 143
holds "a partial run names how many modules reported" "ASKED OF 1 MODULE(S) OF $modules"
lacks "a partial run does not claim they held" "they held"
lacks "a partial run is not reported as nothing at all" "NEVER ASKED"

# 5. THE CONTROL ON THE VINTAGE, and it is the one that keeps the four above from being about
# existence rather than freshness. Reports are on disk and old, and the stub writes none: this
# must read as unasked. A subject that checked only whether the files exist passes cases 1 and 2
# and fails here, and cases 3 and 4 would already have been produced by the `age_them` above --
# which is why that helper ages rather than deletes.
run_case 0 0
holds "reports from an earlier run do not count as this run's" "THE FLOORS WERE NEVER ASKED"

# 6. KILLED WHILE RUNNING, which is the shape the log of 2026-09-19 came from and the one shape
# where a verdict can only come from a trap. Without it the run that most needs an answer is the
# run that prints nothing. The stub sleeps so there is something to interrupt, and the subject is
# sent the signal the supervising harness sends.
cat > "$work/bin/slow-stub" <<'STUB'
#!/bin/sh
sleep 30
STUB
chmod +x "$work/bin/slow-stub"
age_them
STUB_ROOT="$root" STUB_REPORTS=0 STUB_EXIT=0 COVERAGE_GATE_SBT="$work/bin/slow-stub" \
    sh "$subject" > "$work/killed.log" 2>&1 &
killed=$!
# Long enough for the subject to install its traps and reach the build, and no longer: a signal
# arriving before the trap is set kills the shell outright and the case would then be asserting
# that a dead process prints nothing.
sleep 1
kill -TERM "$killed" 2>/dev/null || true
wait "$killed" 2>/dev/null || true
report=$(cat "$work/killed.log")
holds "a run killed part way still prints a verdict" "THE FLOORS WERE NEVER ASKED"
holds "and says it was interrupted" "interrupted"

# 7. THE EXIT STATUS IS THE BUILD'S. A wrapper that swallowed it would make every one of the
# verdicts above advisory, and the gate would pass in CI while printing that it had not run.
age_them
STUB_ROOT="$root" STUB_REPORTS=0 STUB_EXIT=7 COVERAGE_GATE_SBT="$work/bin/sbt-stub" \
    sh "$subject" >/dev/null 2>&1 || passed=$?
check "the build's exit status reaches the caller" "${passed:-0}" "7"

summarise
