package garden.xeno.symbolum.kernel

import org.scalacheck.Gen
import org.scalatest.flatspec.AnyFlatSpec
import org.scalatest.matchers.should.Matchers
import org.scalatestplus.scalacheck.ScalaCheckDrivenPropertyChecks

/**
 * The invariants the kernel relies on, over generated terms rather than chosen ones.
 *
 * The example-based suites fix the cases someone thought of. These fix the claims the rest of the
 * kernel is written against: that a term built through the constructors has the type it was asked
 * for, that substitution preserves it, and that abstracting a variable and applying the result
 * back to it returns what went in. Every rule in [[Kernel]] assumes all three and none of them
 * re-checks any.
 *
 * The generator only produces well-typed terms, which is the point: it is a second implementation
 * of the typing discipline, and where it disagrees with [[Term.typeOf]] one of the two is wrong.
 */
class TermPropertySpec extends AnyFlatSpec with Matchers with ScalaCheckDrivenPropertyChecks {


  /**
   * Abstraction, forced.
   *
   * `Term.abs` refuses a body that is not locally closed, since 2026-09-10, so it returns a
   * refusal like `app` and `eq` do. Every body below is built out of variables and constants a
   * line or two above and none of them can be open, so forcing here is reading the signature and
   * not ignoring it. A test that meant to hand it an open body says so by calling `Term.abs`
   * directly and looking at the `Left`.
   */
  private def lam(variable: FVar, body: Term): Term =
    Term.abs(variable, body).fold(error => fail(s"unexpected refusal: $error"), identity)

  /**
   * ScalaTest's default is ten cases, which is a smoke test rather than a property check.
   *
   * The count below was measured, before 2026-09-14 where this repository's history begins: no
   * property here took longer than a second at it and the module's whole suite ran in six. Raise
   * it if a property starts failing intermittently, which would mean the shapes that break it are
   * rarer than this count reaches.
   */
  implicit override val generatorDrivenConfig: PropertyCheckConfiguration =
    PropertyCheckConfiguration(minSuccessful = 200)

  private val alpha = TyVar("A")

  private val types: Vector[Type] = Vector(
    Type.Bool,
    alpha,
    Type.fun(Type.Bool, Type.Bool),
    Type.fun(alpha, Type.Bool)
  )

  private def variablesAt(ty: Type): Vector[FVar] =
    Vector("a", "b", "c").map(Term.variable(_, ty))

  /** A constructor refusing here means the generator built something ill-typed, not a test failure. */
  private def built(result: Either[KernelError, Term]): Term =
    result.fold(error => sys.error(s"the generator produced an ill-typed term: ${error.message}"), identity)

  /**
   * A well-typed term of exactly the type asked for.
   *
   * Applications are generated by choosing the argument type first and asking for a function into
   * the wanted type, so the result type is known before either half exists. That is what lets the
   * first property below be an equality rather than a check that nothing threw.
   */
  private def termOf(ty: Type, depth: Int): Gen[Term] = {
    val atom: Gen[Term] = Gen.oneOf(variablesAt(ty))

    if (depth <= 0) atom
    else {
      val application: Gen[Term] = for {
        domain <- Gen.oneOf(types)
        fn <- termOf(Type.fun(domain, ty), depth - 1)
        argument <- termOf(domain, depth - 1)
      } yield built(Term.app(fn, argument))

      val lambda: List[Gen[Term]] = Type.destFun(ty).toList.map { case (domain, codomain) =>
        for {
          variable <- Gen.oneOf(variablesAt(domain))
          body <- termOf(codomain, depth - 1)
        } yield lam(variable, body)
      }

      val equation: List[Gen[Term]] =
        if (ty != Type.Bool) Nil
        else List(for {
          operandType <- Gen.oneOf(types)
          left <- termOf(operandType, depth - 1)
          right <- termOf(operandType, depth - 1)
        } yield built(Term.eq(left, right)))

      val choices = (3, atom) :: (2, application) :: (lambda ++ equation).map((2, _))
      Gen.frequency(choices*)
    }
  }

  private val typedTerms: Gen[(Type, Term)] =
    for {
      ty <- Gen.oneOf(types)
      term <- termOf(ty, 3)
    } yield (ty, term)

  "A term built through the constructors" should "have the type it was built at" in {
    forAll(typedTerms) { case (ty, term) =>
      Term.typeOf(term) shouldBe ty
    }
  }

  it should "have no index without a binder over it" in {
    // typeOf raises rather than returning for a dangling index, so reaching a type at all is the
    // assertion. Stated separately from the one above because it is a different invariant: that
    // one is about agreement, this one is about well-formedness.
    forAll(typedTerms) { case (_, term) =>
      noException should be thrownBy Term.typeOf(term)
    }
  }

  "Substitution" should "preserve the type of the term it rewrites" in {
    forAll(typedTerms) { case (ty, term) =>
      val substitution: Map[FVar, Term] =
        Term.freeVariables(term).map(variable => variable -> Term.variable("z", variable.ty)).toMap

      Term.substitute(substitution, term).map(Term.typeOf) shouldBe Right(ty)
    }
  }

  it should "remove every variable it was given" in {
    forAll(typedTerms) { case (_, term) =>
      val substitution: Map[FVar, Term] =
        Term.freeVariables(term).map(variable => variable -> Term.variable("z", variable.ty)).toMap
      val substituted = Term.substitute(substitution, term)

      substituted.map(Term.freeVariables(_).map(_.name)) shouldBe
        Right(if (Term.freeVariables(term).isEmpty) Set.empty else Set("z"))
    }
  }

  "Type instantiation" should "give a term whose type is the instantiated one" in {
    forAll(typedTerms) { case (ty, term) =>
      val instance = Map("A" -> Type.Bool)

      Term.typeOf(Term.substituteTypes(instance, term)) shouldBe Type.substitute(instance, ty)
    }
  }

  "Abstracting a variable and applying the result to it" should "give back the term" in {
    // Over a variable that actually occurs where there is one: closing and reopening a term with
    // no occurrence of the variable would hold for a broken implementation too.
    forAll(typedTerms) { case (_, term) =>
      val variable = Term.freeVariables(term).headOption.getOrElse(Term.variable("w", Type.Bool))
      val applied = Term.app(lam(variable, term), variable)

      applied.map(Term.betaReduce) shouldBe Right(Some(term))
    }
  }

  /**
   * `App` and `Abs` keep the hash they compute when built, and that is sound only if a term equal
   * to another has the same kept hash however it was built. The term compared here is rebuilt by
   * abstracting a variable out of it and reducing the application back, so it is a new object
   * made of new nodes, which the first assertion checks rather than assumes: two references to
   * one object would pass the second for any hash at all.
   */
  "A term's kept hash" should "be the same for an equal term built another way" in {
    forAll(typedTerms) { case (_, term) =>
      val variable = Term.freeVariables(term).headOption.getOrElse(Term.variable("w", Type.Bool))
      val rebuilt = Term.app(lam(variable, term), variable).toOption.flatMap(Term.betaReduce)
        .getOrElse(fail("the round trip above did not come back"))
      whenever(term.isInstanceOf[App] || term.isInstanceOf[Abs]) {
        (rebuilt eq term) shouldBe false
        rebuilt shouldBe term
        rebuilt.hashCode shouldBe term.hashCode
        term.hashCode shouldBe scala.util.hashing.MurmurHash3.productHash(term.asInstanceOf[Product])
      }
    }
  }

  "The order on terms" should "call two terms equal exactly when they are equal" in {
    // Hypothesis sets are kept sorted and duplicate-free by this order. An order that called two
    // distinct hypotheses equal would make the set depend on the route a proof took.
    forAll(typedTerms, typedTerms) { (first, second) =>
      (Term.ordering.compare(first._2, second._2) == 0) shouldBe (first._2 == second._2)
    }
  }

  it should "be antisymmetric" in {
    forAll(typedTerms, typedTerms) { (first, second) =>
      Term.ordering.compare(first._2, second._2).sign shouldBe
        -Term.ordering.compare(second._2, first._2).sign
    }
  }

  "Reflexivity" should "prove an equation about whatever term it is given" in {
    forAll(typedTerms) { case (_, term) =>
      Term.destEq(Kernel.refl(term).conclusion) shouldBe Some((term, term))
    }
  }
}
