package garden.xeno.symbolum.tactics

import garden.xeno.symbolum.checker.{Check, Replayed}
import garden.xeno.symbolum.kernel.*
import garden.xeno.symbolum.theories.Generated

/**
 * The command that writes the generated tables of `docs/evaluation.md`.
 *
 * That document is where the measurements of this system live, and on 2026-09-11 one change to
 * `Conv.refl` made seventeen of its figures stale across five documents. Three of the seventeen
 * were caught by a test. The other fourteen were found by hand with `grep`, and one of them was not
 * a number at all but a sentence: the document said that induction over the naturals "is a hand
 * derivation and rewrites nothing, so it is exactly what it was", which was true of the repair
 * before it and false of that one, because a hand derivation builds the same leaves as any other
 * proof.
 *
 * The three tables below are functions of the code, so they are written by the code.
 *
 *   - **the second reading**, every proof `ReplaySpec` puts to `modules/checker`, with the steps and
 *     the axioms the checker counts for itself. Not `Derivation.size`: the column belongs to the
 *     second reader, and the whole of what the section claims is that something other than the
 *     kernel counted them;
 *   - **the serialised proof**, the three figures `SerialisedSpec` measures on `12 * 12 = 144`;
 *   - **the census**, what the vendored ring corpus is made of, rule by rule.
 *
 * == Why it lives in a test scope ==
 *
 * Because its sources do. The corpus reader, the ring corpus, the list of replayed proofs and the
 * checker's own tests are all test code, and a generator is a measurement rather than a library:
 * nothing published depends on it, and the alternative is moving a corpus reader into a module's
 * main scope so that a document can be printed.
 *
 * The one thing this cannot be is two commands. `docs/evaluation.md` is one artifact and it is
 * regenerated by one command, which is why `build.sbt` puts the checker's tests on this module's
 * test classpath rather than splitting the file between two generators.
 */
object Evaluation {

  /** Where the tables go, relative to the repository root. */
  val Document: String = "docs/evaluation.md"

  /** The command that runs this, written here so that the document and the message cannot drift. */
  val Command: String = "sbt \"tactics/Test/runMain garden.xeno.symbolum.tactics.Evaluation\""

  /** Track R': every proof the checker replays, with what it counted. */
  val Replay: Generated = Generated("replay", Document, Command)

  /** The three figures measured on a proof that left the process as text. */
  val Serialisation: Generated = Generated("serialisation", Document, Command)

  /** What the ring corpus is made of, rule by rule. */
  val Census: Generated = Generated("census", Document, Command)

  /**
   * The verdict the checker returns for one replayed proof, or why there is no table.
   *
   * A refusal is a failure of the generator rather than a row saying so. A document that printed
   * "refused" in a cell would be a document reporting that this system's second reader rejects its
   * own proofs, which is a thing to stop for and not a thing to typeset.
   */
  private def verdict(entry: Replayed.Entry): Either[String, Check.Holds] =
    Check.proof(entry.theorem, entry.theory) match {
      case holds: Check.Holds => Right(holds)
      case Check.Fails(step, rule, why) =>
        Left(s"${entry.label}: the checker refused a $rule step, expecting $why, on ${step.conclusion}")
      case Check.RestsOnUnvouched(axiom, _) =>
        Left(s"${entry.label}: the proof rests on $axiom, which its theory does not assert")
    }

  /** Where the wrong claims put to the rule check live, and the shape their names have. */
  private val Refusals: String = "modules/checker/src/test/scala/garden/xeno/symbolum/checker/CheckSpec.scala"

  /**
   * How many wrong claims are put to the rule check, counted from the tests that put them.
   *
   * A count of tests rather than of code, which is why the row carrying it in the document names
   * the population it counted: the cases in `CheckSpec` whose name says the checker refuses
   * something. A refusal test phrased another way is not in this number and is not claimed to be.
   * The row said nine and that file held eleven, which is what an uncounted count does.
   */
  private def refusalsExercised(): Either[String, Int] =
    try {
      val source = new String(
        java.nio.file.Files.readAllBytes(java.nio.file.Paths.get(Refusals)),
        java.nio.charset.StandardCharsets.UTF_8
      )
      Right("should \"be refused".r.findAllIn(source).size)
    } catch {
      case failure: java.io.IOException =>
        Left(s"$Refusals could not be read: ${failure.getMessage}")
    }

  /**
   * The second reading: what was replayed, and what the second reader counted for each proof.
   *
   * Two tables, because they answer two questions and the first of them is the population. A count
   * of replayed theorems is a claim about a list, and the list is `garden.xeno.symbolum.checker.Replayed`;
   * the document said nine while three files each held a list of their own.
   *
   * The axiom count is written in bold when it is zero, which is the one piece of typesetting this
   * generator does and it is load-bearing: the prose under the table calls the last row the
   * finding, and the finding is that induction over the naturals reaches no axiom while the
   * successor's properties, immediately above it, reach both.
   */
  def replayTable(): Either[String, String] =
    for {
      counted <- Replayed.entries
        .foldLeft[Either[String, Vector[(Replayed.Entry, Check.Holds)]]](Right(Vector.empty)) {
          (acc, entry) => for { rows <- acc; holds <- verdict(entry) } yield rows :+ ((entry, holds))
        }
      refusals <- refusalsExercised()
    } yield {
      val population = Generated.table(
        Vector("", ""),
        Vector(
          Vector("theorems replayed here", counted.size.toString),
          Vector("wrong claims put to the rule check, in `CheckSpec`", refusals.toString)
        )
      )

      val perProof = Generated.table(
        Vector("Theorem", "Inferences", "Axioms reached"),
        counted.map { case (entry, holds) =>
          Vector(
            entry.label,
            holds.steps.toString,
            if (holds.axioms.isEmpty) "**0**" else holds.axioms.size.toString
          )
        }
      )

      s"$population\n\n$perProof"
    }

  /**
   * What one proof costs as text, which is the question of whether the format is usable at all.
   *
   * The sharing figure is measured against what a writer without it would have emitted, and not
   * against the step count. The step count was the comparison until 2026-09-11, when the rewriter
   * stopped building idle steps: the vocabulary of terms did not shrink with the proof, and a proxy
   * that had held only because redundant steps reuse terms came out the wrong way round.
   */
  def serialisationTable(): Either[String, String] = {
    val entry = Replayed.entry(Replayed.Serialised)
    val text = Proof.write(entry.theorem)

    val terms = text.linesIterator.count(_.startsWith("t "))
    val steps = text.linesIterator.count(_.startsWith("s "))
    val written = Replayed.nodesOf(entry.theorem)

    if (steps == 0) Left(s"${entry.label} wrote no steps at all, so there is nothing to report")
    else
      Right(
        Generated.table(
          Vector("Measured on " + entry.label, "As text"),
          Vector(
            Vector("steps, and the distinct terms they are written over", s"$steps steps, $terms terms"),
            Vector(
              "the nodes a writer without sharing would have emitted",
              f"$written nodes, a sharing factor of ${written.toDouble / terms}%.1f"
            ),
            Vector(
              "its size",
              f"${text.length} characters, ${text.length.toDouble / steps}%.1f a step"
            )
          )
        )
      )
  }

  /**
   * The census over the ring corpus, and the total it has to add up to.
   *
   * The total is printed under the table rather than left to the reader, because the defect this
   * replaces was exactly that: a census summing to 196623 beside a total line reading 153953, both
   * hand-copied, each stale from a different day.
   */
  def censusTable(): Either[String, String] = {
    val proofs = RingCost.proved.size
    val total = RingCost.inferences
    val reflexivity = RingCost.census.collectFirst { case ("Reflexivity", count) => count }.getOrElse(0)

    if (RingCost.census.isEmpty) Left("the ring corpus produced no proof at all, so there is no census")
    else
      Right(
        Generated.table(
          Vector("rule", s"inferences over the $proofs proofs"),
          RingCost.census.map { case (rule, count) => Vector(RingCost.inWords(rule), count.toString) }
        ) + f"\n\nThey add up to $total%d inferences, of which $reflexivity%d are reflexivity, " +
          f"${100.0 * reflexivity / total}%.1f%% of the corpus."
      )
  }

  /** Every generated section of the document. */
  def sections(): Either[String, Vector[(Generated, String)]] =
    for {
      replay <- replayTable()
      serialisation <- serialisationTable()
      census <- censusTable()
    } yield Vector(Replay -> replay, Serialisation -> serialisation, Census -> census)

  def main(arguments: Array[String]): Unit =
    sections() match {
      case Left(why) =>
        System.err.println(s"$Document was not rewritten: $why")
        sys.exit(1)
      case Right(sections) => Generated.run(arguments, Document, sections)
    }
}
