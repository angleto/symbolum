package garden.xeno.symbolum.tactics

import java.nio.file.{Files, Path, Paths}
import scala.annotation.tailrec
import scala.jdk.CollectionConverters.*
import org.scalatest.flatspec.AnyFlatSpec
import org.scalatest.matchers.should.Matchers

/**
 * Whether a reader who starts at the front page can reach the rest of it.
 *
 * The documentation is a hierarchy rather than a heap of files beside each other, and the thing
 * that makes it one is that every part is reached from the part above. Nothing enforced that, and
 * the way it fails is silent: a document is written, it is correct, it is generated and pinned by
 * its own test, and no path from `README.md` arrives at it. `docs/lemmas.md` was in exactly that
 * state -- the library of every proved lemma, 567 lines, regenerated by a command and compared by
 * `LibrarySpec`, and unreachable from the door.
 *
 * == Why a walk and not a list ==
 *
 * A list of documents that ought to be linked is a second copy of the thing it checks, and the
 * repository has five instances of what that costs. The walk asks the reader's question instead:
 * start where a reader starts, follow what is written, and see what is never arrived at. A document
 * added and never linked fails this, and so does a link written to a file that has been moved.
 *
 * == What it does not cover ==
 *
 * **Reachable is not findable.** A document at the end of a chain of five links is reachable and
 * nobody will find it. What that wants is an index with one line per document saying which question
 * it answers, which is `994aa06c`'s second level and is not written yet; this is the floor under
 * it, not a substitute for it.
 *
 * **It reads links, not prose.** A document named in a sentence without a link is invisible here,
 * and so is a link to the right file under a name that describes the wrong thing.
 *
 * **It runs last.** This is a file scan that needs nothing from any module, and it sits in the
 * module at the top of the graph, so it does not run on a day the prover does not compile. The
 * repository has that argument written down in the other direction, for `mark`, which is a module
 * of its own precisely so that a check over two files under `docs/` keeps running when the prover
 * is broken. `StyleSpec`, `SourceLanguageSpec` and `DocumentationSpec` are all here and all have
 * the same gap; moving the four of them is its own piece of work and not this one.
 */
class DocumentationMapSpec extends AnyFlatSpec with Matchers {

  /** The front page, which is where a reader starts and therefore where the walk starts. */
  private val Door = "README.md"

  /**
   * A markdown link's target, with the anchor cut off.
   *
   * Only the inline form, `](target)`, because that is the only form this repository writes, and a
   * pattern that accepted reference-style links as well would be a pattern nothing exercises.
   * `LinkShapes` below is what says the reading is right, on the shapes that are actually written.
   */
  private val Link = """\]\(\s*([^)\s#]+)""".r

  private def read(path: String): String =
    Files.readString(Paths.get(path))

  /** Where a link written in `from` points, as a path from the repository root. */
  private def targetOf(from: String, written: String): String =
    Paths.get(from).getParent match {
      case null => Paths.get(written).normalize.toString
      case here => here.resolve(written).normalize.toString
    }

  private def linksIn(path: String): Vector[String] =
    Link
      .findAllMatchIn(read(path))
      .map(_.group(1))
      .filterNot(target =>
        target.startsWith("http://") || target.startsWith("https://") || target.startsWith("mailto:")
      )
      .map(targetOf(path, _))
      .toVector

  private def markdownIn(directory: String): Vector[String] = {
    val root = Paths.get(directory)
    if (!Files.exists(root)) Vector.empty
    else {
      val stream = Files.walk(root)
      try
        stream
          .iterator()
          .asScala
          .toVector
          .filter(path => path.toString.endsWith(".md"))
          .map(_.toString)
          .sorted
      finally stream.close()
    }
  }

  /** What the walk arrived at, and what it found written and could not arrive at. */
  private final case class Walk(reached: Set[String], broken: Vector[(String, String)])

  private lazy val walk: Walk = {
    @tailrec
    def go(pending: List[String], reached: Set[String], broken: Vector[(String, String)]): Walk =
      pending match {
        case Nil => Walk(reached, broken)
        case here :: rest =>
          val (found, missing) = linksIn(here).partition(target => Files.exists(Paths.get(target)))

          // A link to a directory reaches the documents in it, because that is what a reader
          // clicking `docs/adr/` gets. Without this every decision record would read as unreachable
          // and the assertion below would be about the listing rather than about the reader.
          val opened = found.flatMap { target =>
            if (Files.isDirectory(Paths.get(target))) markdownIn(target) else Vector(target)
          }

          val fresh = opened.filterNot(reached.contains)
          go(
            rest ++ fresh.filter(_.endsWith(".md")).toList,
            reached ++ fresh,
            broken ++ missing.map(here -> _)
          )
      }

    go(List(Door), Set(Door), Vector.empty)
  }

  /* ----------------------------------------------------- the walk can see something */

  // Measured on 2026-09-15: 29 markdown files under `docs/`, 20 of them decision records, and the
  // walk reaches 28 of the 29 from the door. Floors rather than equalities, because documents are
  // added; what a floor rules out is the walk that read nothing, which would pass every assertion
  // below it in silence.
  "The walk" should "have found the documents, which is how a check like this passes for free" in {
    withClue(s"markdown under docs/: ${markdownIn("docs").size}\n") {
      markdownIn("docs").size should be >= 20
    }

    withClue(s"reached from $Door: ${walk.reached.size}\n") {
      walk.reached.size should be >= 20
    }

    info(s"${walk.reached.size} files reached from $Door, ${markdownIn("docs").size} under docs/")
  }

  it should "read a link where one is written and nowhere else" in {
    // The pattern is the whole instrument, so it is pointed at what it must find and at what it
    // must not. An image, a bare URL and an anchor are the three that would quietly widen or
    // narrow the walk.
    Link.findAllMatchIn("see [the guide](docs/proving.md) for it").map(_.group(1)).toVector shouldBe
      Vector("docs/proving.md")

    Link.findAllMatchIn("[a section](#getting-it)").map(_.group(1)).toVector shouldBe empty
    Link.findAllMatchIn("no links at all, just prose").map(_.group(1)).toVector shouldBe empty

    // Relative to the file the link is written in, not to the root: a link in `docs/proving.md` to
    // `adr/0003.md` is `docs/adr/0003.md`, and reading it as `adr/0003.md` would report every
    // cross-reference inside `docs/` as broken.
    targetOf("docs/proving.md", "adr/0003.md") shouldBe "docs/adr/0003.md"
    targetOf("docs/proving.md", "../README.md") shouldBe "README.md"
    targetOf(Door, "docs/lemmas.md") shouldBe "docs/lemmas.md"
  }

  /* ------------------------------------------------------------------- the two checks */

  "Every document under docs/" should "be reachable by following links from the front page" in {
    val unreachable = markdownIn("docs").filterNot(walk.reached.contains)

    withClue(
      s"${unreachable.size} document(s) no reader starting at $Door arrives at. Link each from " +
        s"the document above it in the hierarchy, or from the table in $Door:\n" +
        s"${unreachable.mkString("\n")}\n"
    ) {
      unreachable shouldBe empty
    }
  }

  "Every link a document writes" should "point at something that is there" in {
    val broken = walk.broken.map { case (from, target) => s"$from -> $target" }

    withClue(s"${broken.size} broken link(s):\n${broken.mkString("\n")}\n") {
      broken shouldBe empty
    }
  }

  /* ------------------------------------------------- the symbols a reader meets first */

  /**
   * Every spelling the parser reads is explained where a reader is sent to look it up.
   *
   * `docs/notation.md` is the page the front page points an unfamiliar reader at, and the thing
   * that would make it useless is the ordinary one: the parser gains a symbol, nobody adds a row,
   * and the page keeps reading as though it were complete. So the population is taken from the
   * **generated** table in `docs/reading-register.md`, which `Register` writes from
   * `Notation.standard`, rather than from a list kept here.
   *
   * What this deliberately does not check is precedence, and `notation.md` deliberately does not
   * carry it: one row per spelling already exists in the register, generated, and a second copy
   * beside it is the defect this repository has recorded five times. This asserts that the symbol
   * is **explained**, not that its precedence is repeated.
   */
  "Every symbol the parser reads" should "be explained in the page a reader is sent to" in {
    val register = read("docs/reading-register.md")
    val notation = read("docs/notation.md")

    // `| \`notation infix ==> via ==>\` | ...` — the spelling is the third word of the key.
    // The trailing backtick of the key is stripped: a binder's key ends `notation binder \`` and
    // a greedy `\\S+` takes the delimiter with it, which put `!\``, `?\`` and `\\\`` on the first
    // failing list and sent the reader looking for symbols that do not exist.
    val spellings = "\\| `notation (?:infix|prefix|binder) (\\S+)".r
      .findAllMatchIn(register)
      .map(_.group(1).stripSuffix("`"))
      .toVector
      .distinct

    // The floor that says the table was read at all. **Seventeen**, and the gap from the table's 27
    // rows is the interesting part: the register has one row per (spelling, constant) PAIR, so `+`
    // is two rows, the reals' and `num`'s, and so are `*`, `<`, `<=`, `>` and `>=`. That is
    // `docs/adr/0018` visible in a count.
    //
    // This number was written 20 first, from the row count, and then 18, from a run whose regex was
    // still taking the key's closing backtick as part of the spelling and so counted `-` twice. Both
    // were pinned before being measured and this clue caught both. It is measured now:
    //
    //     grep -oE '\| `notation (infix|prefix|binder) [^ ]+' docs/reading-register.md \
    //       | awk '{print $NF}' | sed 's/`$//' | sort -u | wc -l
    withClue("the register's notation table was not read; the shape of its key must have moved: ") {
      spellings.size should be >= 17
    }

    // Explained means "appears as a token inside a code span", not "appears somewhere in the file":
    // `-` and `/` occur inside prose and inside other symbols, so a substring test passes for a
    // symbol nothing documents. A binder is glued to its variable in `\\x. e`, so a token that
    // STARTS with the spelling counts, which is why this is a prefix test and not an equality.
    val spans = "`([^`]+)`".r.findAllMatchIn(notation).map(_.group(1)).toVector
    val tokens = spans.flatMap(_.split("\\s+")).toSet

    val unexplained = spellings.filterNot(symbol => tokens.exists(_.startsWith(symbol)))

    withClue(
      s"${unexplained.size} spelling(s) the parser reads and `docs/notation.md` does not " +
        s"explain: ${unexplained.mkString(", ")}. Add a row saying what each MEANS; its " +
        s"precedence belongs in the register's generated table and nowhere else.\n"
    ) {
      unexplained shouldBe empty
    }
  }

  /** The turnstile, which is the one piece of notation no document defined until 2026-09-16. */
  it should "explain the turnstile, which is what a sequent is written with" in {
    val notation = read("docs/notation.md")

    notation should include("|-")
    notation.toLowerCase should include("sequent")

    // Not vacuous: `|-` appears in the guide and on the front page dozens of times, and appearing
    // is what it did for as long as neither explained it.
    read("docs/proving.md") should include("|-")
  }
}
